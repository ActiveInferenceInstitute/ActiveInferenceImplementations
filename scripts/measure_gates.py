"""Run the gate arms and record their measured numbers in one generated page.

`docs/gate-timings.md` is the single place where arm wall times and test counts
live. This script produces it by running `./run.sh <arm>` for every measured
arm, so no number in the document is hand-typed. `--check` (the `docs` arm of
`./run.sh`) verifies instead that every arm `./run.sh --list` reports has a row
in the page; it never runs an arm.

Usage:
    python3 scripts/measure_gates.py            # refresh docs/gate-timings.md
    python3 scripts/measure_gates.py --check    # arms and page agree

Exit codes: 0 success (all arms passed / the page is current), 1 failure.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import platform
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "gate-timings.md"
RECEIPT = ROOT / "_build" / "gnn" / "validation-receipt.json"
MEASURED = ("lint", "test-fast", "test", "docs", "gnn", "notebooks")
LAST_SUMMARY = re.compile(r"Test Summary:")
SUMMARY_ROW = re.compile(r"\|\s*(\d+)\s+(\d+)\s")


def run(argv: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(argv, cwd=ROOT, capture_output=True, text=True, check=False)


def arms() -> list[str]:
    completed = run(["bash", "run.sh", "--list"])
    if completed.returncode != 0:
        raise SystemExit(f"run.sh --list failed: {completed.stderr.strip()}")
    return [line.strip() for line in completed.stdout.splitlines() if line.strip()]


def version(command: list[str]) -> str:
    completed = run(command)
    if completed.returncode != 0:
        return "unavailable"
    return (completed.stdout or completed.stderr).splitlines()[0].strip()


def julia_counts(output: str) -> str:
    """Return the pass count of the last Julia test summary, if any."""

    matches = list(LAST_SUMMARY.finditer(output))
    if not matches:
        return ""
    tail = output[matches[-1].end() :]
    for line in tail.splitlines()[1:]:
        row = SUMMARY_ROW.search(line)
        if row:
            return f"{row.group(1)} pass"
        if line.strip() and "|" not in line:
            break
    return ""


def gnn_version() -> str:
    if not RECEIPT.is_file():
        return ""
    receipt = json.loads(RECEIPT.read_text(encoding="utf-8"))
    pin = receipt.get("pin", {})
    commit = str(pin.get("commit", ""))[:12]
    return f"gnn {receipt.get('gnn_version', '?')} (pin {commit})"


def measure(arm: str) -> dict[str, str]:
    started = time.monotonic()
    completed = run(["bash", "run.sh", arm])
    elapsed = time.monotonic() - started
    output = completed.stdout + completed.stderr
    result = ""
    if arm in ("test-fast", "test"):
        result = julia_counts(output)
    elif arm == "gnn" and completed.returncode == 0:
        result = gnn_version()
    elif arm == "notebooks" and completed.returncode == 0:
        result = "2 notebooks executed"
    elif completed.returncode == 0:
        result = "ok"
    if completed.returncode != 0:
        result = (result + " " if result else "") + f"exit {completed.returncode}"
    return {
        "arm": arm,
        "status": "pass" if completed.returncode == 0 else "FAIL",
        "seconds": f"{elapsed:.1f}",
        "result": result or "-",
    }


def render(rows: list[dict[str, str]], all_arms: list[str]) -> str:
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    head = run(["git", "rev-parse", "--short", "HEAD"]).stdout.strip() or "unknown"
    environment = [
        ("Commit", head),
        ("Measured", stamp),
        ("Host", platform.platform()),
        ("Julia", version(["julia", "--version"])),
        ("Python", version([sys.executable, "--version"])),
        ("uv", version(["uv", "--version"])),
    ]
    lines = [
        "# Gate timings and test counts",
        "",
        "<!-- Generated by `python3 scripts/measure_gates.py`; do not hand-edit. -->",
        "",
        "One row per arm of [`../run.sh`](../run.sh), measured by running the arm on",
        "this host, one run each. Runtimes provisioned by `setup` and `gnn` are",
        "reused between runs; a first run that has to download them is slower and",
        "is not the steady-state number. `./run.sh docs` fails when an arm reported by",
        "`./run.sh --list` has no row here, so this page cannot silently drift from",
        "the entry point.",
        "",
        "Refresh it with:",
        "",
        "```sh",
        "python3 scripts/measure_gates.py",
        "```",
        "",
        "The pre-change baseline those arms replaced is recorded in",
        "[`gate-baseline.md`](gate-baseline.md).",
        "",
        "## Environment",
        "",
        "| Item | Value |",
        "| --- | --- |",
    ]
    lines.extend(f"| {key} | {value} |" for key, value in environment)
    lines += [
        "",
        "## Arms",
        "",
        "| Arm | Command | Status | Wall time (s) | Result |",
        "| --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        lines.append(
            f"| `{row['arm']}` | `./run.sh {row['arm']}` | {row['status']} | "
            f"{row['seconds']} | {row['result']} |"
        )
    unmeasured = [arm for arm in all_arms if arm not in MEASURED]
    if unmeasured:
        lines += ["", "## Not measured", "", "| Arm | Reason |", "| --- | --- |"]
        reasons = {
            "setup": "environment provisioning; not a gate",
            "gate": "runs every measured arm in sequence",
        }
        for arm in unmeasured:
            lines.append(f"| `{arm}` | {reasons.get(arm, 'aggregate arm')} |")
    lines += [
        "",
        "Julia counts come from the last `Test Summary` block, which aggregates the",
        "nested testsets of the run; the full suite includes the fast static gates,",
        "so its count is the sum of the static and inference tests.",
        "",
    ]
    return "\n".join(lines)


def check(all_arms: list[str]) -> int:
    if not DOC.is_file():
        print(f"{DOC.relative_to(ROOT)} is missing; run python3 scripts/measure_gates.py", file=sys.stderr)
        return 1
    text = DOC.read_text(encoding="utf-8")
    missing = [arm for arm in all_arms if f"| `{arm}` |" not in text]
    if missing:
        print(f"{DOC.relative_to(ROOT)} has no row for: {', '.join(missing)}", file=sys.stderr)
        print("refresh it with python3 scripts/measure_gates.py", file=sys.stderr)
        return 1
    if "Generated by `python3 scripts/measure_gates.py`" not in text:
        print(f"{DOC.relative_to(ROOT)} lost its generated-file marker", file=sys.stderr)
        return 1
    print(f"gate timings page: ok ({len(all_arms)} arms)")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the page lists every arm")
    args = parser.parse_args(argv)

    all_arms = arms()
    if args.check:
        return check(all_arms)

    if not DOC.is_file():
        # The `docs` arm checks this page, so it must exist before the arms run.
        placeholder = [
            {"arm": arm, "status": "pending", "seconds": "-", "result": "-"}
            for arm in MEASURED
        ]
        DOC.parent.mkdir(parents=True, exist_ok=True)
        DOC.write_text(render(placeholder, all_arms) + "\n", encoding="utf-8")

    rows = [measure(arm) for arm in MEASURED]
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(render(rows, all_arms) + "\n", encoding="utf-8")
    for row in rows:
        print(f"{row['arm']:>10}  {row['status']:<4}  {row['seconds']:>6}s  {row['result']}")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0 if all(row["status"] == "pass" for row in rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
